# 1. Display text
print("Python is running!")

# 2. Perform calculations
a = 15
b = 5

print("Addition:", a + b)
print("Division:", a / b)

# 3. Use a condition
if a > b:
    print("a is greater than b")

# 4. Repeat an operation
for number in range(1, 4):
    print("Iteration:", number)
